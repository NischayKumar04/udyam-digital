const STRINGS: Record<string, Strings> = { English: en, Hindi: hi, Tamil: ta, Kannada: kn };

export type StringKey = keyof Strings;

export function translator(language: string) {
  const strings = STRINGS[language] ?? en;
  return (key: StringKey, values: Record<string, string | number> = {}) =>
    Object.entries(values).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), strings[key]);
}

export function formatDate(iso: string, language: string) {
  const locale = LANGUAGES.find((l) => l.name === language)?.locale ?? "en-IN";
  return new Date(`${iso}T00:00:00`).toLocaleDateString(locale, { day: "numeric", month: "short" });
}
